from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, create_model

from api.schemas.document import DocumentTypeDTO, ProjectDocumentDTO
from api.schemas.ingest import (
    IngestCompleted,
    IngestError,
    IngestJobDTO,
    IngestJobEventDTO,
    IngestProgress,
    IngestStarted,
    IngestStatusDTO,
)
from api.schemas.project import ProjectCreateDTO, ProjectDTO
from api.schemas.upload import UploadResponseDTO

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "ui" / "src" / "types" / "generated.ts"
JSON2TS = REPO_ROOT / "ui" / "node_modules" / ".bin" / "json2ts"

BANNER = """/* tslint:disable */
/* eslint-disable */
/**
 * This file is auto-generated by server/scripts/export_schema.py.
 * Do not edit by hand - update the Pydantic DTOs and re-run the generator.
 */"""

# Interfaces emitted in the main body, in this exact order.
BODY_MODELS: list[type[BaseModel]] = [
    ProjectDTO,
    ProjectCreateDTO,
    DocumentTypeDTO,
    ProjectDocumentDTO,
    UploadResponseDTO,
    IngestJobDTO,
    IngestStatusDTO,
    IngestJobEventDTO,
]

# SSE payloads pinned for the discriminated union, in this exact order.
PINNED_MODELS: list[type[BaseModel]] = [
    IngestStarted,
    IngestProgress,
    IngestCompleted,
    IngestError,
]

# Discriminated unions appended after the pinned block; member order is fixed.
UNIONS: list[tuple[str, list[str]]] = [
    ("IngestEvent", [m.__name__ for m in PINNED_MODELS]),
]


def _strip_titles(node: Any) -> None:
    if isinstance(node, dict):
        node.pop("title", None)
        for value in node.values():
            _strip_titles(value)
    elif isinstance(node, list):
        for value in node:
            _strip_titles(value)


def _bundle_schema(models: list[type[BaseModel]], root_name: str) -> dict[str, Any]:
    fields = {model.__name__: (model, ...) for model in models}
    bundle = create_model(root_name, __config__=ConfigDict(extra="forbid"), **fields)
    schema = bundle.model_json_schema()
    _strip_titles(schema)
    for key, definition in schema.get("$defs", {}).items():
        definition["title"] = key
    schema["title"] = root_name
    return schema


def _run_json2ts(schema: dict[str, Any]) -> str:
    if not JSON2TS.exists():
        raise FileNotFoundError(
            f"json2ts not found at {JSON2TS}. Run `npm install` in ui/ first."
        )
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as handle:
        json.dump(schema, handle)
        schema_path = handle.name
    result = subprocess.run(
        [str(JSON2TS), "-i", schema_path, "--bannerComment", ""],
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def _parse_interfaces(ts: str) -> dict[str, str]:
    blocks: dict[str, str] = {}
    lines = ts.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("export interface "):
            name = line[len("export interface ") :].split()[0]
            start = index
            while not lines[index].rstrip() == "}":
                index += 1
            blocks[name] = "\n".join(lines[start : index + 1])
        index += 1
    return blocks


def _render(models: list[type[BaseModel]], root_name: str) -> list[str]:
    blocks = _parse_interfaces(_run_json2ts(_bundle_schema(models, root_name)))
    return [blocks[model.__name__] for model in models]


def render() -> str:
    parts: list[str] = [BANNER, ""]
    parts.append("\n\n".join(_render(BODY_MODELS, "GeneratedBundle")))
    parts.append("")
    parts.append("// ---- Types pinned by scripts/export_schema.py ----")
    parts.append("")
    parts.append("\n\n".join(_render(PINNED_MODELS, "PinnedBundle")))
    parts.append("")
    parts.append("// ---- Discriminated unions (appended by scripts/export_schema.py) ----")
    parts.append("")
    for name, members in UNIONS:
        union = [f"export type {name} ="]
        union.extend(f"  | {member}" for member in members)
        union[-1] = union[-1] + ";"
        parts.append("\n".join(union))
    return "\n".join(parts) + "\n"


def main() -> None:
    OUTPUT.write_text(render())
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
