def _strip_titles(node: Any) -> None:
    # Strip only the JSON-schema `title` *metadata* (always a string), never a model
    # field literally named `title` (whose value is its sub-schema dict, e.g.
    # ConversationRead.title). Popping the latter silently drops the field from the
    # generated types.
    if isinstance(node, dict):
        if isinstance(node.get("title"), str):
            node.pop("title", None)
        for value in node.values():
            _strip_titles(value)
    elif isinstance(node, list):
        for value in node:
            _strip_titles(value)


def _inline_enums(schema: dict[str, Any]) -> dict[str, Any]:
    """Replace $refs to pure-enum $defs with the enum inline, so json2ts emits a
    string-literal union (e.g. "queued" | "running") rather than a named type.
    Only the rendered models are kept downstream, so a named-type $def would dangle;
    inlining matches the established generated.ts convention. Object $defs (e.g.
    ChatMessage) keep their $ref and are emitted as their own interface."""
    defs = schema.get("$defs", {})
    enum_defs = {
        name: {k: v for k, v in body.items() if k != "title"}
        for name, body in defs.items()
        if "enum" in body and "properties" not in body
    }

    def walk(node: Any) -> Any:
        if isinstance(node, dict):
            ref = node.get("$ref", "")
            name = ref.removeprefix("#/$defs/")
            if name in enum_defs:
                return dict(enum_defs[name])
            return {key: walk(value) for key, value in node.items()}
        if isinstance(node, list):
            return [walk(value) for value in node]
        return node

    rewritten = walk(schema)
    for name in enum_defs:
        rewritten.get("$defs", {}).pop(name, None)
    return rewritten


def _bundle_schema(models: list[type[BaseModel]], root_name: str) -> dict[str, Any]:
    fields = {model.__name__: (model, ...) for model in models}
    bundle = create_model(root_name, __config__=ConfigDict(extra="forbid"), **fields)
    schema = bundle.model_json_schema()
    _strip_titles(schema)
    for key, definition in schema.get("$defs", {}).items():
        definition["title"] = key
    schema["title"] = root_name
    return _inline_enums(schema)


def _run_json2ts(schema: dict[str, Any]) -> str:
    if not JSON2TS.exists():
        raise FileNotFoundError(
            f"json2ts not found at {JSON2TS}. Run `npm install` in ui/ first."
        )
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as handle:
        json.dump(schema, handle)
        schema_path = handle.name
    result = subprocess.run(
        [str(JSON2TS), "-i", schema_path, "--bannerComment", ""],
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def _parse_interfaces(ts: str) -> dict[str, str]:
    blocks: dict[str, str] = {}
    lines = ts.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("export interface "):
            name = line[len("export interface ") :].split()[0]
            start = index
            while not lines[index].rstrip() == "}":
                index += 1
            blocks[name] = "\n".join(lines[start : index + 1])
        index += 1
    return blocks


def _render(models: list[type[BaseModel]], root_name: str) -> list[str]:
    blocks = _parse_interfaces(_run_json2ts(_bundle_schema(models, root_name)))
    return [blocks[model.__name__] for model in models]


def render() -> str:
    parts: list[str] = [BANNER, ""]
    parts.append("\n\n".join(_render(BODY_MODELS, "GeneratedBundle")))
    parts.append("")
    parts.append("// ---- Types pinned by scripts/export_schema.py ----")
    parts.append("")
    parts.append("\n\n".join(_render(PINNED_MODELS, "PinnedBundle")))
    parts.append("")
    parts.append("// ---- Discriminated unions (appended by scripts/export_schema.py) ----")
    parts.append("")
    for name, members in UNIONS:
        union = [f"export type {name} ="]
        union.extend(f"  | {member}" for member in members)
        union[-1] = union[-1] + ";"
        parts.append("\n".join(union))
    return "\n".join(parts) + "\n"


def main() -> None:
    OUTPUT.write_text(render())
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
